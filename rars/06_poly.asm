# Задача: вычислить P(x)=a*x^3+b*x^2+c*x+d двумя способами.
# a=2, b=3, c=4, d=5, x=2. Не функция: все числа заданы в регистрах.
.text
.globl main

main:
    li a0, 2            # a
    li a1, 3            # b
    li a2, 4            # c
    li a3, 5            # d
    li a4, 2            # x
   
    # Прямое вычисление (с повторным использованием x^2).
    mul t0, a4, a4      # x^2 = 4
    mul t1, t0, a4      # x^3 = 8
    mul t1, a0, t1      # a*x^3 = 16
    mul t2, a1, t0      # b*x^2 = 12
    add t1, t1, t2      # 28
    mul t2, a2, a4      # c*x = 8
    add t1, t1, t2      # 36
    add t3, t1, a3      # 41: прямой результат
   
    # Схема Горнера: ((a*x+b)*x+c)*x+d.
    mul t4, a0, a4      # 4
    add t4, t4, a1      # 7
    mul t4, t4, a4      # 14
    add t4, t4, a2      # 18
    mul t4, t4, a4      # 36
    add t4, t4, a3      # 41: результат Горнера
    mv  a0, t4

    # Служебные инструкции RARS: напечатать a0 и завершить программу.
    # Пока считаем их готовым шаблоном, механизм ecall изучим позже.
    li a7, 1
    ecall
    li a7, 10
    ecall

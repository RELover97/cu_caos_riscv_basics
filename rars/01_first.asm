# Задача: вычислить 19 + 23. Режим RV64.
.text
.globl main
main:
    addi t0, zero, 19   # t0 = 19; x0 (zero) всегда равен нулю
    addi t1, zero, 23   # t1 = 23
    add  t2, t0, t1     # t2 = 42; исходные регистры не меняются
    mv   a0, t2         # передать результат в готовый шаблон вывода

    # Служебные инструкции RARS: напечатать a0 и завершить программу.
    # Пока считаем их готовым шаблоном, механизм ecall изучим позже.
    li a7, 1
    ecall
    li a7, 10
    ecall

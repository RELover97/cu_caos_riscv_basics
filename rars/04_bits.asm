# Задача: изменить биты условного регистра настроек.
# Бит 0 = питание, бит 1 = звук, бит 2 = запись.
.text
.globl main
main:

    li   t0, 5          # 0b101: питание и запись включены
    
    ori  t1, t0, 2      # 0b111: включить звук (маска 1 << 1)
   
    # signed extension of -5
    andi t2, t1, -5     # 0b011: сбросить запись (маска ~4 = -5)
    
    xori t3, t2, 1      # 0b010: переключить питание (маска 1)

    # узнать состояние звука
    # shift right logical immediate
    srli t4, t3, 1      # переместить нужный бит в позицию 0
    andi t4, t4, 1      # t4 = 1: звук включён
 
    li   t5, -8
 
    srli t6, t5, 1      # 0x7ffffffffffffffc: заполняем нулями
    # shift right arytmetic immediate
    srai a1, t5, 1      # 0xfffffffffffffffc: копируем знак (-4)
    mv   a0, t3         # итоговая маска 2

    # Служебные инструкции RARS: напечатать a0 и завершить программу.
    # Пока считаем их готовым шаблоном, механизм ecall изучим позже.
    li a7, 1
    ecall
    li a7, 10
    ecall

# Задача: получить 0x12345678 и увидеть разложение li.
.text
.globl main
main:
    # у addi число занимает 12 бит со знаком -> диапазон [−2048, 2047]
    # li = load immediate
    li   t0, 0x12345678 # Псевдоинструкция: ассемблер подберёт команды
    
    # 0x12345678 = 0x12345 * 2^12 + 0x678
    # load upper immediate
    lui  t1, 0x12345    # t1 = 0x12345000 (верхние 20 бит)
    addi t1, t1, 0x678  # t1 = 0x12345678 (младшие 12 бит)
   
    # Если младшие 12 бит >= 0x800, addi воспринимает их как отрицательные (signed immediate!)
    # 0xabc не помещается в signed 12 bit immediate 
    # => 0x12345abc = 0x12346000 − 0x544
    li   t2, 0x12345abc # Вручную тот же результат:

    lui  t3, 0x12346    # Округляем верхнюю часть вверх
    addi t3, t3, -1348  # 0xabc - 0x1000 = -1348
    sub  a0, t0, t1     # 0: первый способ и второй совпадают

    # Служебные инструкции RARS: напечатать a0 и завершить программу.
    # Пока считаем их готовым шаблоном, механизм ecall изучим позже.
    li a7, 1
    ecall
    li a7, 10
    ecall
